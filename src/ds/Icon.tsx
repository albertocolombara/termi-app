export function Icon({ name, size, color }: IconProps) {
  const def: IconDef = ICONS[name];
  const s = size ?? def.size ?? def.box;
  return (
    <Svg width={s} height={s} viewBox={`0 0 ${def.box} ${def.box}`}>
      <G>{def.draw(color ?? def.color)}</G>
    </Svg>
  );
}

