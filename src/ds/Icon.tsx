/**
 * Termi · Painel de partidas (Figma v3): o painel de aeroporto de placas giratórias, com os "olhos"
 * em placas amarelas. É o ícone dos avisos em voo, no lugar da mala (direção visual com menos foco no
 * mascote). Desenhado por código a partir da grade do Figma.
 */
export function PainelDePartidas({ size = 36 }: { size?: number }) {
  const colunas = 9;
  const linhas = 6;
  const olhos = new Set(['1,2', '2,2', '3,2', '1,5', '2,5', '3,5']);
  const placas: React.ReactNode[] = [];
  for (let l = 0; l < linhas; l++) {
    for (let c = 0; c < colunas; c++) {
      const x = 5.31 + c * 3.256;
      const y = 8.47 + l * 3.494;
      placas.push(<Rect key={`${l},${c}`} x={x} y={y} width={2.97} height={3.2} rx={0.37} fill={olhos.has(`${l},${c}`) ? C.accent.default : PLACA} />);
      placas.push(<Rect key={`d${l},${c}`} x={x} y={y + 1.56} width={2.97} height={0.08} fill={DOBRA} />);
    }
  }
  return (
    <Svg width={size} height={size} viewBox="0 0 36 36">
      <Rect width={36} height={36} rx={4} fill={C.surface.subtle} />
      <Rect x={4.26} y={7.41} width={27.74} height={22.88} rx={1.64} fill={ARO} />
      <Defs>
        <ClipPath id="visorDoPainel">
          <Rect x={4.94} y={8.17} width={26.46} height={21.34} rx={1.19} />
        </ClipPath>
      </Defs>
      <Rect x={4.94} y={8.17} width={26.46} height={21.34} rx={1.19} fill={VISOR} />
      <G clipPath="url(#visorDoPainel)">{placas}</G>
    </Svg>
  );
}

// Cores locais da ilustração do painel (Figma: "Termi · Painel de partidas").
const ARO = '#252529';
const VISOR = '#09090A';
const PLACA = '#222325';
const DOBRA = '#0C0C0D';
